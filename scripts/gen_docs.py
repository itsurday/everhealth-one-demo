"""Generates living documentation from metadata into docs/generated/.

Usage:
    python scripts/gen_docs.py           # (re)write the docs
    python scripts/gen_docs.py --check   # exit 1 if the committed docs are stale (used in CI)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import eh_metadata as md  # noqa: E402

OUT_DIR = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "docs", "generated"))
HEADER = "<!-- Generated by scripts/gen_docs.py from force-app metadata. Do not edit by hand. -->\n\n"


def cell(value):
    return (value or "").replace("|", "\\|").replace("\n", " ")


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(cell(str(v)) for v in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def field_inventory(src):
    out = [HEADER, "# Field Inventory\n\n",
           "Every custom field in source, with its data-sensitivity labels (`securityClassification` / `complianceGroup`).\n",
           "No PHI or payment-data fields exist by design. Custom Metadata fields have no sensitivity label (config, not data).\n\n"]
    by_object = {}
    for f in md.fields(src):
        by_object.setdefault(f["object"], []).append(f)
    for obj, fs in by_object.items():
        out.append(f"## {obj}\n\n")
        rows = []
        for f in fs:
            keys = ", ".join(k for k, on in (("External ID", f["external_id"]), ("Unique", f["unique"])) if on)
            rows.append((f"`{f['api']}`", f["label"], f["type"] + (f" ({keys})" if keys else ""),
                         f["sensitivity"] or "n/a", f["compliance"] or "", f["description"]))
        out.append(table(["Field", "Label", "Type", "Sensitivity", "Compliance", "Description"], rows) + "\n")
    return "".join(out)


def flow_catalog(src):
    out = [HEADER, "# Flow & Automation Catalog\n\n",
           "One owner per automated process (see docs/STA.md §4). Record-triggered, scheduled and screen flows, ",
           "the approval process and Apex triggers.\n\n## Flows\n\n"]
    out.append(table(["Flow", "Trigger", "Object", "Status", "Purpose"],
                     [(f"`{f['name']}`", f"{f['trigger']} {f['detail']}".strip(), f["object"] or "-", f["status"], f["description"])
                      for f in md.flows(src)]))
    out.append("\n## Approval processes\n\n")
    out.append(table(["Approval process", "Object", "Active", "Purpose"],
                     [(f"`{a['name']}`", a["object"], a["active"], a["description"]) for a in md.approval_processes(src)]))
    out.append("\n## Apex triggers\n\n")
    out.append(table(["Trigger", "Definition"], [(f"`{t['name']}`", f"`{t['header']}`") for t in md.triggers(src)]))
    return "".join(out)


def report_index(src):
    out = [HEADER, "# Report & Dashboard Index\n\n## Reports\n\n"]
    out.append(table(["Report", "Folder", "Report type", "Grouped by", "Purpose"],
                     [(r["name"], r["folder"], r["report_type"], ", ".join(g.split("$")[-1] for g in r["groupings"]), r["description"])
                      for r in md.reports(src)]))
    out.append("\n## Dashboards\n\n")
    for d in md.dashboards(src):
        out.append(f"### {d['title']}\n\n{d['description']}\n\n")
        out.append(table(["Component", "Type", "Source report"], d["components"]) + "\n")
    return "".join(out)


def mapping_matrix(src):
    out = [HEADER, "# GTM Field Mapping Matrix (simulated systems)\n\n",
           "Rendered from `Field_Mapping__mdt`. Policy and lifecycle mapping: docs/SYNC_RULES.md.\n\n"]
    rows = sorted(md.field_mappings(src), key=lambda m: (m.get("System__c", ""), m.get("SF_Object__c", ""), m.get("SF_Field__c", "")))
    out.append(table(["System", "Salesforce field", "External field", "Direction", "Winning system", "Conflict rule", "Notes"],
                     [(m.get("System__c"), f"{m.get('SF_Object__c')}.{m.get('SF_Field__c')}", m.get("External_Field__c"),
                       m.get("Direction__c"), m.get("Winning_System__c"), m.get("Conflict_Rule__c"), m.get("Notes__c")) for m in rows]))
    return "".join(out)


DOCS = {
    "FIELD_INVENTORY.md": field_inventory,
    "FLOW_CATALOG.md": flow_catalog,
    "REPORT_INDEX.md": report_index,
    "MAPPING_MATRIX.md": mapping_matrix,
}


def render_all(src=md.DEFAULT_SRC):
    return {name: build(src) for name, build in DOCS.items()}


def main(argv):
    rendered = render_all()
    if "--check" in argv:
        stale = []
        for name, text in rendered.items():
            path = os.path.join(OUT_DIR, name)
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current != text:
                stale.append(name)
        if stale:
            print("Stale generated docs: " + ", ".join(stale) + ". Run: python scripts/gen_docs.py")
            return 1
        print("Generated docs are up to date.")
        return 0
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, text in rendered.items():
        with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote docs/generated/" + name)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
